let cached: Recipe[] | null = null;

/** 厳選レシピを Recipe[] として返す（id は "curated:xxx" で安定）。 */
export function curatedRecipes(): Recipe[] {
  if (cached) return cached;
  cached = SEEDS.map((s) => {
    const now = 0; // 固定（毎回同じ id・内容になるよう createdAt も固定）
    return {
      id: `curated:${s.id}`,
      titleJa: s.ja,
      titleDe: s.de,
      sourceUrl: "",
      imageDataUrl: "",
      timeMinutes: s.time,
      difficulty: s.diff,
      tags: s.tags,
      status: "want" as const,
      memo: "",
      ingredients: s.ing.map(([nameJa, nameDe, amount], i) => ({
        id: `curated:${s.id}:ing${i}`,
        nameJa,
        nameDe,
        amount,
        order: i,
      })),
      steps: s.steps.map(([textJa, textDe], i) => ({
        id: `curated:${s.id}:step${i}`,
        textJa,
        textDe,
        order: i,
      })),
      createdAt: now,
      updatedAt: now,
      category: s.cat,
      seasonMonths: s.season,
      servings: s.servings,
      emoji: s.emoji,
    } satisfies Recipe;
  });
  return cached;
}

/** 厳選レシピを自分のレシピへ複製する用に、新しい id を振った Recipe を作る。 */
export function cloneCuratedForSave(r: Recipe, newId: () => string): Recipe {
  const now = Date.now();
  return {
    ...r,
    id: newId(),
    ingredients: r.ingredients.map((i, idx) => ({ ...i, id: newId(), order: idx })),
    steps: r.steps.map((s, idx) => ({ ...s, id: newId(), order: idx })),
    createdAt: now,
    updatedAt: now,
  };
}
